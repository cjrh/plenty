#!/usr/bin/env python3
"""Experiment-only specialization of a field-only Plenty class into columns.

This deliberately is not a Plenty parser or a public clist implementation.
The generated module is compiled and borrow-checked by the ordinary compiler.
"""
import argparse
from pathlib import Path
import re

PRIMITIVES = {"bool", "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64"}
NAME = r"[A-Za-z][A-Za-z0-9_]*"


def schema(source):
    lines = [line for line in source.splitlines() if line.strip() and not line.lstrip().startswith("#")]
    if not lines or not (match := re.fullmatch(rf"pub class ({NAME}):", lines[0])):
        raise ValueError("expected one public, nongeneric, field-only class")
    name = match[1]
    fields = []
    for line in lines[1:]:
        field = re.fullmatch(rf"    pub ({NAME}): ({NAME})", line)
        if not field or field[2] not in PRIMITIVES:
            raise ValueError("only public primitive fields are supported; methods/destructors and owned fields are excluded")
        if field[1] in {n for n, _ in fields}:
            raise ValueError("duplicate field")
        fields.append((field[1], field[2]))
    if not fields:
        raise ValueError("at least one primitive field is required")
    return name, fields


def generate(source):
    row, fields = schema(source)
    owner = f"Clist{row}"
    error = f"Append{row}Error"
    lines = ["# Generated by the experiment-only generate.py; ordinary Plenty.", source.strip(), "",
             f"pub enum {error}:", f"    Allocation(AllocError, {row})", "",
             f"pub class {owner}:"]
    lines += [f"    _{name}: list[{ty}]" for name, ty in fields]
    lines += ["", f"    pub def __init__(self: &mut {owner}) -> Result[(), AllocError]:"]
    lines += [f"        self._{name} = list[{ty}].new()?" for name, ty in fields]
    lines += ["        Ok(())", "", "    pub def len(self) -> i64:", f"        len(self._{fields[0][0]})", "",
              f"    pub def reserve(self: &mut {owner}, additional: i64) -> Result[(), AllocError]:"]
    lines += [f"        self._{name}.reserve(additional)?" for name, _ in fields]
    lines += ["        Ok(())", "",
              f"    pub def append(self: &mut {owner}, row: {row}) -> Result[(), {error}]:",
              "        match self.reserve(1):", "            case Err(error):",
              f"                return Err({error}.Allocation(error, row))", "            case Ok(done):", "                ()"]
    # Scalar append cannot allocate after reserve; unwrap documents that invariant.
    lines += [f"        self._{name}.append(row.{name}).unwrap()" for name, _ in fields]
    lines += ["        Ok(())", "", f"    pub def copy_row(self, index: i64) -> Option[{row}]:",
              "        position = index + self.len() if index < 0 else index",
              "        if position < 0 or position >= self.len():", "            return Nothing",
              f"        Some({row}(" + ", ".join(f"self._{name}[position]" for name, _ in fields) + "))"]
    for name, ty in fields:
        lines += ["", f"    pub def get_{name}(self, index: i64) -> {ty}:", f"        self._{name}[index]", "",
                  f"    pub def set_{name}(self: &mut {owner}, index: i64, value: {ty}) -> ():",
                  f"        self._{name}[index] = value", "",
                  f"    pub def column_{name}(self) -> &list[{ty}]:", f"        &self._{name}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.schema.read_text()))


if __name__ == "__main__":
    main()
