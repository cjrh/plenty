#!/usr/bin/env python3
"""Assemble the publishable agent-skills tree: OUT_DIR [--version X.Y.Z].

`agent-skills/` holds the hand-written files of the plentylang/skills
repository. This script copies them, replaces `@VERSION@` with the compiler
version, and adds reference pages generated from the book, so the bundled
cheat sheet, signature index and module pages always match the compiler they
ship beside. Links between bundled pages become relative links inside OUT_DIR;
links to other book pages are reduced to their text, since the published tree
must not depend on this repository.
"""

import argparse
import json
from pathlib import Path
import posixpath
import re
import shutil
import sys
import tomllib
from urllib.parse import urlsplit

from check_links import INLINE_LINK, prose

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "agent-skills"
BOOK = REPO / "book/src"
SKILL = "skills/plenty/references"

# Book path (file or directory, relative to book/src) -> path in OUT_DIR.
BUNDLE = {
    "design/examples/cheatsheet.md": f"{SKILL}/cheatsheet.md",
    "design/toolchain/01-building/packages.md": f"{SKILL}/packages.md",
    "design/stdlib": f"{SKILL}/std",
    "design/facilities/01-builtins": f"{SKILL}/builtins",
    "design/facilities/02-io": f"{SKILL}/io",
}

# Paragraphs addressed to compiler contributors, dropped from bundled pages.
CONTRIBUTOR_NOTES = re.compile(r"\n\n[^\n]*(?:\n[^\n]+)*UPDATE_STDLIB_INDEX[^\n]*(?:\n[^\n]+)*")


def compiler_version():
    return tomllib.loads((REPO / "Cargo.toml").read_text())["package"]["version"]


def bundled_pages():
    """Every bundled book page (relative to book/src) -> its output path."""
    pages = {}
    for book_path, output in BUNDLE.items():
        source = BOOK / book_path
        if source.is_dir():
            for page in sorted(source.rglob("*.md")):
                relative = page.relative_to(source).as_posix()
                pages[f"{book_path}/{relative}"] = f"{output}/{relative}"
        elif source.is_file():
            pages[book_path] = output
        else:
            raise SystemExit(f"bundled book path is missing: {book_path}")
    return pages


def link_end(markdown, start):
    """Index just past the `)` closing the link destination starting at `start`."""
    depth = 1
    index = start
    while index < len(markdown):
        char = markdown[index]
        if char == "\\":
            index += 2
            continue
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise ValueError("unterminated link")


def link_start(markdown, close):
    """Index of the `[` that opens the link text ending at `close`."""
    depth = 1
    index = close - 1
    while index >= 0:
        char = markdown[index]
        if char == "]":
            depth += 1
        elif char == "[" and (index == 0 or markdown[index - 1] != "\\"):
            depth -= 1
            if depth == 0:
                return index
        index -= 1
    raise ValueError("link text has no opening bracket")


def rewrite_links(markdown, page, pages):
    """Retarget links of book page `page` for its bundled copy."""
    output_dir = posixpath.dirname(pages[page])
    visible = prose(markdown)
    pieces = []
    position = 0
    for match in INLINE_LINK.finditer(visible):
        target = match[1] or match[2]
        parts = urlsplit(target)
        if parts.scheme or parts.netloc or not parts.path:
            continue
        close = match.start()
        opening = link_start(visible, close)
        end = link_end(visible, match.start() + 2)
        text = markdown[opening + 1:close]
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(page), parts.path))
        fragment = "#" + parts.fragment if parts.fragment else ""
        if resolved in pages:
            relative = posixpath.relpath(pages[resolved], output_dir)
            replacement = f"[{text}]({relative}{fragment})"
        else:
            # Images would be lost; the bundled pages have none today.
            if opening > 0 and markdown[opening - 1] == "!":
                raise ValueError(f"{page}: image {target} is not bundled")
            replacement = text
        pieces.append(markdown[position:opening])
        pieces.append(replacement)
        position = end
    pieces.append(markdown[position:])
    return "".join(pieces)


def generated_page(page, pages, version):
    markdown = (BOOK / page).read_text()
    markdown = CONTRIBUTOR_NOTES.sub("", markdown)
    markdown = re.sub(r"<!-- Generated by [^>]*-->\n\n?", "", markdown)
    body = rewrite_links(markdown, page, pages)
    header = (
        f"<!-- Generated from the Plenty {version} book page {page}. "
        "Edit the book, not this copy. -->\n\n"
    )
    return header + body


def build(out_dir, version):
    out_dir = Path(out_dir)
    if out_dir.exists():
        if any(out_dir.iterdir()) and not (out_dir / ".claude-plugin").is_dir():
            raise SystemExit(f"{out_dir} exists and is not a skills tree; refusing to replace it")
        shutil.rmtree(out_dir)
    for source in sorted(SOURCE.rglob("*")):
        if source.is_dir():
            continue
        destination = out_dir / source.relative_to(SOURCE)
        destination.parent.mkdir(parents=True, exist_ok=True)
        if source.suffix in (".md", ".json"):
            destination.write_text(source.read_text().replace("@VERSION@", version))
        else:
            shutil.copy2(source, destination)
    pages = bundled_pages()
    for page, output in pages.items():
        destination = out_dir / output
        if destination.exists():
            raise SystemExit(f"generated page {output} would replace a hand-written file")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(generated_page(page, pages, version))
    for manifest in (out_dir / ".claude-plugin").glob("*.json"):
        json.loads(manifest.read_text())
    return out_dir


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out_dir")
    parser.add_argument("--version", default=None, help="defaults to Cargo.toml's version")
    arguments = parser.parse_args(argv)
    version = arguments.version or compiler_version()
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise SystemExit(f"version must be MAJOR.MINOR.PATCH: {version}")
    print(build(arguments.out_dir, version))


if __name__ == "__main__":
    sys.exit(main())
