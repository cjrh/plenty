#!/usr/bin/env python3
"""Regenerate the Unicode and HTML entity tables in stdlib/std/markdown.plenty.

The tables sit between the BEGIN/END GENERATED TABLES markers. They come from
Python's `unicodedata` and `html.entities.html5`, so the Unicode version is the
one this Python ships; the script prints it. Run from the repository root:

    python3 -B scripts/gen_markdown_tables.py [--check]
"""

import argparse
import html.entities
import pathlib
import sys
import unicodedata

MODULE = pathlib.Path(__file__).resolve().parent.parent / "stdlib/std/markdown.plenty"
BEGIN = "# BEGIN GENERATED TABLES"
END = "# END GENERATED TABLES"
RANGES_PER_CHUNK = 48


def literal(data: bytes) -> str:
    out = []
    for byte in data:
        if 0x20 <= byte < 0x7F and byte not in (0x22, 0x5C):
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02x}")
    return 'b"' + "".join(out) + '"'


def punctuation_ranges() -> list[tuple[int, int]]:
    ranges: list[list[int]] = []
    previous = False
    for code in range(128, 0x110000):
        current = unicodedata.category(chr(code))[0] in "PS"
        if current and previous:
            ranges[-1][1] = code
        elif current:
            ranges.append([code, code])
        previous = current
    return [(low, high) for low, high in ranges]


def punctuation_tables() -> list[str]:
    ranges = punctuation_ranges()
    chunks = [ranges[i : i + RANGES_PER_CHUNK] for i in range(0, len(ranges), RANGES_PER_CHUNK)]
    lines = [
        "# Non-ASCII Unicode P and S ranges: six bytes each, low then high, big",
        "# endian, sorted. `punctuation_chunk` picks the chunk that may hold `code`.",
        "def punctuation_chunk(code: i64) -> i64:",
    ]
    for index, chunk in enumerate(chunks[1:], start=1):
        keyword = "if" if index == 1 else "elif"
        lines.append(f"    {keyword} code < {chunk[0][0]}:")
        lines.append(f"        return {index - 1}")
    lines.append(f"    {len(chunks) - 1}")
    lines.append("")
    lines.append("def punctuation_ranges(chunk: i64) -> bytes:")
    lines.append("    match chunk:")
    for index, chunk in enumerate(chunks):
        data = b"".join(low.to_bytes(3, "big") + high.to_bytes(3, "big") for low, high in chunk)
        lines.append(f"        case {index}:")
        lines.append(f"            {literal(data)}")
    lines.append("        case _:")
    lines.append('            b""')
    return lines


def entity_tables() -> list[str]:
    buckets: dict[str, list[tuple[str, bytes]]] = {}
    for name, value in sorted(html.entities.html5.items()):
        if not name.endswith(";"):
            continue
        stem = name[:-1]
        buckets.setdefault(stem[0], []).append((stem[1:], value.encode("utf-8")))
    lines = [
        "# HTML5 named character references, grouped by first letter. Each record",
        "# is the rest of the name's length, the rest of the name, the value's",
        "# length, and the value in UTF-8.",
        "def entity_bucket(first: i64) -> bytes:",
        "    match first:",
    ]
    for first in sorted(buckets):
        data = b"".join(
            bytes([len(rest)]) + rest.encode("ascii") + bytes([len(value)]) + value
            for rest, value in buckets[first]
        )
        lines.append(f"        case {ord(first)}:")
        lines.append(f"            {literal(data)}")
    lines.append("        case _:")
    lines.append('            b""')
    return lines


# Notices for the source data; the full texts ship in THIRD-PARTY-NOTICES.md
# (see EMBEDDED in scripts/release/third_party_notices.py).
NOTICE = [
    "# Punctuation ranges derive from the Unicode Character Database,",
    "# Copyright (c) 1991-2026 Unicode, Inc., under the Unicode License v3",
    "# (scripts/release/licenses/unicode-license-v3.txt). Named character",
    "# references come from the WHATWG HTML Standard, Copyright (c) WHATWG",
    "# (Apple, Google, Mozilla, Microsoft); as source code they are under the",
    "# BSD 3-Clause License (scripts/release/licenses/whatwg-html-BSD-3-Clause.txt).",
]


def generated() -> str:
    lines = [BEGIN, f"# Generated by scripts/gen_markdown_tables.py from Unicode {unicodedata.unidata_version}."]
    lines.extend(NOTICE)
    lines.append("")
    lines.extend(punctuation_tables())
    lines.append("")
    lines.extend(entity_tables())
    lines.append(END)
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the module is out of date")
    args = parser.parse_args()
    source = MODULE.read_text()
    start = source.index(BEGIN)
    stop = source.index(END) + len(END) + 1
    updated = source[:start] + generated() + source[stop:]
    if args.check:
        if updated != source:
            print(f"{MODULE} tables are out of date", file=sys.stderr)
            return 1
        return 0
    MODULE.write_text(updated)
    print(f"wrote tables from Unicode {unicodedata.unidata_version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
